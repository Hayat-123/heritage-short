#!/usr/bin/env python3
"""
01_keyframes.py — Generate one keyframe image per shot via Cloudflare Workers AI.

Provider:    Cloudflare Workers AI (FLUX.2 klein → FLUX.1 schnell fallback)
Free tier:   ~50–170 images/day, no payment card required
Credentials: Set in environment (never hardcode):
               CLOUDFLARE_ACCOUNT_ID
               CLOUDFLARE_API_TOKEN

If credentials are absent or the API returns an error, the stage exits
cleanly and prints instructions.  The assembly stage will then use the
placeholder images generated by 02_video_fallback.py.

Caching:
    Each image is saved to assets/keyframes/<16-char-hash>.png
    If the file exists the shot is skipped — no API call is made.

Logging:
    Every real API call (hit or miss) is appended to runs.jsonl.

Output resolution:
    16:9  → 1360×768   (closest to 1920×1080 within typical FLUX limits)
    For 9:16 the assembler crops/scales; we don't need a separate keyframe.

Usage:
    python pipeline/01_keyframes.py [--dry-run] [--shot shot_01]

Options:
    --dry-run      Print what would be generated; make no API calls.
    --shot SHOT_ID Generate only the named shot (for testing).
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT))

# Auto-load .env from project root (safe no-op if file is absent or dotenv not installed)
try:
    from dotenv import load_dotenv
    load_dotenv(ROOT / ".env")
except ImportError:
    pass

from pipeline.utils.cache import cache_key, is_cached
from pipeline.utils.logger import log_call

KEYFRAMES_DIR = ROOT / "assets" / "keyframes"

# Cloudflare Workers AI model — flux-1-schnell is the confirmed available model.
# flux-2-klein is not yet on Cloudflare; list it first so we pick it up automatically
# when Cloudflare adds it.
FLUX_MODELS = [
    "@cf/black-forest-labs/flux-2-klein",   # future; 404s gracefully
    "@cf/black-forest-labs/flux-1-schnell", # confirmed available
]

# NOTE: Cloudflare Workers AI FLUX does NOT accept width/height/seed params.
# It accepts only: prompt, steps (1-8).
# The output is always a fixed-size PNG returned as raw bytes.


def _cf_credentials() -> tuple[str, str] | None:
    """Return (account_id, api_token) or None if not configured."""
    account_id = os.environ.get("CLOUDFLARE_ACCOUNT_ID", "").strip()
    api_token  = os.environ.get("CLOUDFLARE_API_TOKEN", "").strip()
    if account_id and api_token:
        return account_id, api_token
    return None


def _generate_image(
    prompt: str,
    seed: int,
    account_id: str,
    api_token: str,
) -> tuple[bytes, str, float]:
    """
    Call Cloudflare Workers AI and return (image_bytes, model_used, latency_s).
    Tries FLUX models in order; raises RuntimeError if all fail.
    """
    import requests  # stdlib-safe import; requests is a standard dep

    for model in FLUX_MODELS:
        url = (
            f"https://api.cloudflare.com/client/v4/accounts/"
            f"{account_id}/ai/run/{model}"
        )
        payload = {
            "prompt": prompt,
            "steps":  4,       # Cloudflare FLUX only accepts prompt + steps (1-8)
        }
        headers = {
            "Authorization": f"Bearer {api_token}",
            "Content-Type":  "application/json",
        }

        t0 = time.perf_counter()
        try:
            resp = requests.post(url, json=payload, headers=headers, timeout=120)
        except requests.RequestException as exc:
            print(f"  Network error for {model}: {exc}")
            continue
        latency = time.perf_counter() - t0

        if resp.status_code == 404:
            print(f"  Model {model} not available, trying next...")
            continue

        if resp.status_code != 200:
            print(f"  API error {resp.status_code}: {resp.text[:300]}")
            continue

        # Check for JSON wrapper first (Cloudflare Workers AI returns {result: {image: <b64>}})
        ct = resp.headers.get("Content-Type", "")
        if "application/json" in ct or resp.content.startswith(b"{"):
            import base64
            data = resp.json()
            b64_img = data.get("result", {}).get("image") or data.get("image")
            if b64_img:
                img_bytes = base64.b64decode(b64_img)
                return img_bytes, model, latency
            print(f"  API returned error/no image: {data.get('errors')}")
            continue

        if ct.startswith("image/") or len(resp.content) > 1000:
            return resp.content, model, latency

        print(f"  Unexpected response (ct={ct}, len={len(resp.content)})")
        continue

    raise RuntimeError("All Cloudflare FLUX models failed or are unavailable.")


def run(dry_run: bool = False, only_shot: str | None = None) -> int:
    storyboard_path = ROOT / "storyboard.json"
    if not storyboard_path.exists():
        print("ERROR: storyboard.json not found. Run 00_validate.py first.", file=sys.stderr)
        return 1

    with storyboard_path.open(encoding="utf-8") as fh:
        storyboard = json.load(fh)

    style_suffix = storyboard["film"]["style"]["suffix"]
    shots = storyboard["shots"]
    if only_shot:
        shots = [s for s in shots if s["id"] == only_shot]
        if not shots:
            print(f"ERROR: shot '{only_shot}' not found in storyboard.", file=sys.stderr)
            return 1

    creds = _cf_credentials()
    if creds is None:
        print(
            "\n⚠  Cloudflare credentials not found.\n"
            "   To enable image generation, set two environment variables:\n\n"
            "     CLOUDFLARE_ACCOUNT_ID=<your_account_id>\n"
            "     CLOUDFLARE_API_TOKEN=<your_api_token>\n\n"
            "   Get them from: https://dash.cloudflare.com/profile/api-tokens\n"
            "   Required permission: 'AI — Workers AI Read'\n\n"
            "   The pipeline will continue with placeholder images.\n"
            "   Run this script again after setting the variables.\n",
            file=sys.stderr,
        )
        return 2  # Soft exit — not a hard error

    if dry_run:
        print("DRY RUN — no API calls will be made.\n")

    KEYFRAMES_DIR.mkdir(parents=True, exist_ok=True)
    account_id, api_token = creds

    ok_count = skip_count = fail_count = 0

    for shot in shots:
        shot_id = shot["id"]
        prompt  = f"{shot['image_prompt']}, {style_suffix}"
        seed    = shot.get("seed", 42)
        key     = cache_key("keyframes", shot, extra={"steps": 4})
        out_path = KEYFRAMES_DIR / f"{key}.png"

        if is_cached(out_path):
            print(f"  [{shot_id}] cache hit → {out_path.name}")
            skip_count += 1
            continue

        print(f"  [{shot_id}] generating keyframe …", end="", flush=True)

        if dry_run:
            print(" (dry-run, skipped)")
            continue

        t_start = time.perf_counter()
        try:
            img_bytes, model_used, latency = _generate_image(prompt, seed, account_id, api_token)
            out_path.write_bytes(img_bytes)

            log_call(
                stage="keyframes",
                shot_id=shot_id,
                model=model_used,
                provider="cloudflare-workers-ai",
                params={"prompt_prefix": prompt[:80], "steps": 4},
                cache_hit=False,
                latency_s=latency,
                cost_usd=0.0,
                cost_note="within Cloudflare Workers AI daily free allowance",
                output_path=out_path.relative_to(ROOT),
                ok=True,
            )
            print(f" ✓ {latency:.1f}s  [{model_used.split('/')[-1]}]  → {out_path.name}")
            ok_count += 1

        except Exception as exc:
            latency = time.perf_counter() - t_start
            log_call(
                stage="keyframes",
                shot_id=shot_id,
                model="unknown",
                provider="cloudflare-workers-ai",
                params={"seed": seed},
                cache_hit=False,
                latency_s=latency,
                cost_usd=0.0,
                cost_note="failed — no charge",
                output_path=None,
                ok=False,
            )
            print(f" ✗ {exc}")
            fail_count += 1

    print(
        f"\nKeyframes: {ok_count} generated, {skip_count} cached, {fail_count} failed."
    )
    return 0 if fail_count == 0 else 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true", help="Print actions without calling API")
    parser.add_argument("--shot", metavar="SHOT_ID", help="Generate only this shot (e.g. shot_03)")
    args = parser.parse_args()
    return run(dry_run=args.dry_run, only_shot=args.shot)


if __name__ == "__main__":
    sys.exit(main())
